package com.hyflip.server.security;

import com.hyflip.server.config.HyFlipProperties;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import org.springframework.http.HttpMethod;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

/**
 * Rejects API requests that do not carry the per-launch token.
 *
 * <p>The server listens on localhost, but any web page open in the user's browser can still send
 * requests to localhost. The token, generated by the desktop app on every launch and known only to
 * the app's webview, keeps those pages from reading the config (including the API key).
 */
@Component
public class AuthTokenFilter extends OncePerRequestFilter {

    public static final String HEADER = "X-HyFlip-Token";

    private final byte[] expected;

    public AuthTokenFilter(HyFlipProperties properties) {
        this.expected = properties.authToken().getBytes(StandardCharsets.UTF_8);
    }

    @Override
    protected boolean shouldNotFilter(HttpServletRequest request) {
        return expected.length == 0
                || !request.getRequestURI().startsWith("/api/")
                || HttpMethod.OPTIONS.matches(request.getMethod());
    }

    @Override
    protected void doFilterInternal(HttpServletRequest request, HttpServletResponse response, FilterChain chain)
            throws ServletException, IOException {
        String token = request.getHeader(HEADER);
        if (token == null || !MessageDigest.isEqual(expected, token.getBytes(StandardCharsets.UTF_8))) {
            response.sendError(HttpServletResponse.SC_UNAUTHORIZED, "Missing or invalid " + HEADER);
            return;
        }
        chain.doFilter(request, response);
    }
}
